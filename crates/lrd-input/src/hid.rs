//! Tabelas USB HID usage (página 0x07) → códigos nativos.
//! O frontend converte `KeyboardEvent.code` para HID (ver `apps/desktop/src/lib/keymap.ts`).

/// HID → (scancode set 1, tecla estendida E0).
pub fn hid_to_windows_scancode(hid: u32) -> Option<(u16, bool)> {
    let n = |s: u16| Some((s, false));
    let e = |s: u16| Some((s, true));
    match hid {
        // Letras A..Z
        0x04 => n(0x1E), 0x05 => n(0x30), 0x06 => n(0x2E), 0x07 => n(0x20), 0x08 => n(0x12),
        0x09 => n(0x21), 0x0A => n(0x22), 0x0B => n(0x23), 0x0C => n(0x17), 0x0D => n(0x24),
        0x0E => n(0x25), 0x0F => n(0x26), 0x10 => n(0x32), 0x11 => n(0x31), 0x12 => n(0x18),
        0x13 => n(0x19), 0x14 => n(0x10), 0x15 => n(0x13), 0x16 => n(0x1F), 0x17 => n(0x14),
        0x18 => n(0x16), 0x19 => n(0x2F), 0x1A => n(0x11), 0x1B => n(0x2D), 0x1C => n(0x15),
        0x1D => n(0x2C),
        // 1..9, 0
        0x1E..=0x26 => n((hid - 0x1E + 0x02) as u16),
        0x27 => n(0x0B),
        0x28 => n(0x1C), // Enter
        0x29 => n(0x01), // Esc
        0x2A => n(0x0E), // Backspace
        0x2B => n(0x0F), // Tab
        0x2C => n(0x39), // Espaço
        0x2D => n(0x0C), // - _
        0x2E => n(0x0D), // = +
        0x2F => n(0x1A), // [ {   (ABNT2: ´ `)
        0x30 => n(0x1B), // ] }   (ABNT2: [ {)
        0x31 => n(0x2B), // \ |
        0x32 => n(0x2B), // Non-US # (ABNT2: ] })
        0x33 => n(0x27), // ; :   (ABNT2: ç)
        0x34 => n(0x28), // ' "   (ABNT2: ~ ^)
        0x35 => n(0x29), // ` ~   (ABNT2: ' ")
        0x36 => n(0x33), // ,
        0x37 => n(0x34), // .
        0x38 => n(0x35), // / ?   (ABNT2: ; :)
        0x39 => n(0x3A), // Caps Lock
        // F1..F10, F11, F12
        0x3A..=0x43 => n((hid - 0x3A + 0x3B) as u16),
        0x44 => n(0x57),
        0x45 => n(0x58),
        0x46 => e(0x37), // Print Screen
        0x47 => n(0x46), // Scroll Lock
        0x49 => e(0x52), // Insert
        0x4A => e(0x47), // Home
        0x4B => e(0x49), // Page Up
        0x4C => e(0x53), // Delete
        0x4D => e(0x4F), // End
        0x4E => e(0x51), // Page Down
        0x4F => e(0x4D), // →
        0x50 => e(0x4B), // ←
        0x51 => e(0x50), // ↓
        0x52 => e(0x48), // ↑
        0x53 => n(0x45), // Num Lock
        0x54 => e(0x35), // Num /
        0x55 => n(0x37), // Num *
        0x56 => n(0x4A), // Num -
        0x57 => n(0x4E), // Num +
        0x58 => e(0x1C), // Num Enter
        0x59 => n(0x4F), 0x5A => n(0x50), 0x5B => n(0x51), // Num 1 2 3
        0x5C => n(0x4B), 0x5D => n(0x4C), 0x5E => n(0x4D), // Num 4 5 6
        0x5F => n(0x47), 0x60 => n(0x48), 0x61 => n(0x49), // Num 7 8 9
        0x62 => n(0x52), // Num 0
        0x63 => n(0x53), // Num ,
        0x64 => n(0x56), // Intl Backslash (ABNT2/ISO: \ |)
        0x65 => e(0x5D), // Menu de contexto
        0x85 => n(0x7E), // Num . (ABNT2)
        0x87 => n(0x73), // Intl Ro (ABNT2: / ?)
        0xE0 => n(0x1D), // Ctrl esq.
        0xE1 => n(0x2A), // Shift esq.
        0xE2 => n(0x38), // Alt esq.
        0xE3 => e(0x5B), // Win esq.
        0xE4 => e(0x1D), // Ctrl dir.
        0xE5 => n(0x36), // Shift dir.
        0xE6 => e(0x38), // Alt dir. / AltGr
        0xE7 => e(0x5C), // Win dir.
        _ => None,
    }
}

/// HID → keycode virtual do macOS (kVK_*).
pub fn hid_to_mac_keycode(hid: u32) -> Option<u16> {
    let k = match hid {
        0x04 => 0x00, 0x05 => 0x0B, 0x06 => 0x08, 0x07 => 0x02, 0x08 => 0x0E, // A B C D E
        0x09 => 0x03, 0x0A => 0x05, 0x0B => 0x04, 0x0C => 0x22, 0x0D => 0x26, // F G H I J
        0x0E => 0x28, 0x0F => 0x25, 0x10 => 0x2E, 0x11 => 0x2D, 0x12 => 0x1F, // K L M N O
        0x13 => 0x23, 0x14 => 0x0C, 0x15 => 0x0F, 0x16 => 0x01, 0x17 => 0x11, // P Q R S T
        0x18 => 0x20, 0x19 => 0x09, 0x1A => 0x0D, 0x1B => 0x07, 0x1C => 0x10, // U V W X Y
        0x1D => 0x06,                                                         // Z
        0x1E => 0x12, 0x1F => 0x13, 0x20 => 0x14, 0x21 => 0x15, 0x22 => 0x17, // 1 2 3 4 5
        0x23 => 0x16, 0x24 => 0x1A, 0x25 => 0x1C, 0x26 => 0x19, 0x27 => 0x1D, // 6 7 8 9 0
        0x28 => 0x24, // Return
        0x29 => 0x35, // Escape
        0x2A => 0x33, // Delete (backspace)
        0x2B => 0x30, // Tab
        0x2C => 0x31, // Space
        0x2D => 0x1B, // -
        0x2E => 0x18, // =
        0x2F => 0x21, // [
        0x30 => 0x1E, // ]
        0x31 => 0x2A, // \
        0x32 => 0x2A, // Non-US #
        0x33 => 0x29, // ;
        0x34 => 0x27, // '
        0x35 => 0x32, // `
        0x36 => 0x2B, // ,
        0x37 => 0x2F, // .
        0x38 => 0x2C, // /
        0x39 => 0x39, // Caps Lock
        0x3A => 0x7A, 0x3B => 0x78, 0x3C => 0x63, 0x3D => 0x76, // F1-F4
        0x3E => 0x60, 0x3F => 0x61, 0x40 => 0x62, 0x41 => 0x64, // F5-F8
        0x42 => 0x65, 0x43 => 0x6D, 0x44 => 0x67, 0x45 => 0x6F, // F9-F12
        0x49 => 0x72, // Insert → Help
        0x4A => 0x73, // Home
        0x4B => 0x74, // Page Up
        0x4C => 0x75, // Forward Delete
        0x4D => 0x77, // End
        0x4E => 0x79, // Page Down
        0x4F => 0x7C, // →
        0x50 => 0x7B, // ←
        0x51 => 0x7D, // ↓
        0x52 => 0x7E, // ↑
        0x53 => 0x47, // Num Lock → Clear
        0x54 => 0x4B, // Num /
        0x55 => 0x43, // Num *
        0x56 => 0x4E, // Num -
        0x57 => 0x45, // Num +
        0x58 => 0x4C, // Num Enter
        0x59 => 0x53, 0x5A => 0x54, 0x5B => 0x55, // Num 1 2 3
        0x5C => 0x56, 0x5D => 0x57, 0x5E => 0x58, // Num 4 5 6
        0x5F => 0x59, 0x60 => 0x5B, 0x61 => 0x5C, // Num 7 8 9
        0x62 => 0x52, // Num 0
        0x63 => 0x41, // Num .
        0x64 => 0x0A, // Intl Backslash (ISO)
        0x67 => 0x51, // Num =
        0x85 => 0x5F, // Num , 
        0x87 => 0x5E, // Intl Ro
        0xE0 => 0x3B, // Control
        0xE1 => 0x38, // Shift
        0xE2 => 0x3A, // Option
        0xE3 => 0x37, // Command
        0xE4 => 0x3E, // Right Control
        0xE5 => 0x3C, // Right Shift
        0xE6 => 0x3D, // Right Option
        0xE7 => 0x36, // Right Command
        _ => return None,
    };
    Some(k)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn letters_and_digits_mapped() {
        for hid in 0x04..=0x27 {
            assert!(hid_to_windows_scancode(hid).is_some(), "win {hid:x}");
            assert!(hid_to_mac_keycode(hid).is_some(), "mac {hid:x}");
        }
        assert_eq!(hid_to_windows_scancode(0x1E), Some((0x02, false))); // 1
        assert_eq!(hid_to_windows_scancode(0x26), Some((0x0A, false))); // 9
        assert_eq!(hid_to_windows_scancode(0x3A), Some((0x3B, false))); // F1
        assert_eq!(hid_to_windows_scancode(0x43), Some((0x44, false))); // F10
    }
}
